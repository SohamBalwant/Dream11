package matchbuddy

import (
	"errors"
	"fmt"
	"sort"
)

// Simplified Dream11-style fantasy cricket scoring rules.
// Rules are deterministic:
// - Batting: +1/run, +4 for four, +6 for six, +8 at 30 runs, +16 at 50 runs (replaces 30), -2 for duck.
// - Bowling: +25 per wicket (excluding run out), +4 per maiden over.
// - Multipliers: Captain x2, Vice-Captain x1.5.

var (
	ErrInvalidTeamSize    = errors.New("fantasy team must have exactly 11 players")
	ErrDuplicatePlayer    = errors.New("duplicate player in fantasy team")
	ErrUnknownPlayer      = errors.New("player not found in squad")
	ErrMaxPlayersFromTeam = errors.New("cannot pick more than 7 players from one real team")
	ErrCaptainNotSelected = errors.New("captain must be one of the 11 players")
	ErrVCNotSelected      = errors.New("vice-captain must be one of the 11 players")
	ErrCaptainVCSame      = errors.New("captain and vice-captain must be different players")
)

// PlayerRunningStats tracks in-match progress for milestone evaluations.
type PlayerRunningStats struct {
	Runs               int     `json:"runs"`
	BallsFaced         int     `json:"balls_faced"`
	Fours              int     `json:"fours"`
	Sixes              int     `json:"sixes"`
	Wickets            int     `json:"wickets"`
	OversBowled        int     `json:"overs_bowled"`
	BallsBowledInOver  int     `json:"balls_bowled_in_over"`
	RunsConcededInOver int     `json:"runs_conceded_in_over"`
	IsOut              bool    `json:"is_out"`
	Milestone30Awarded bool    `json:"milestone_30_awarded"`
	Milestone50Awarded bool    `json:"milestone_50_awarded"`
	TotalPoints        float64 `json:"total_points"`
}

// RankChange captures position movements on the room leaderboard.
type RankChange struct {
	UserID      string  `json:"user_id"`
	Username    string  `json:"username"`
	OldRank     int     `json:"old_rank"`
	NewRank     int     `json:"new_rank"`
	PointsDelta float64 `json:"points_delta"`
	NewTotal    float64 `json:"new_total"`
}

// ValidateTeam ensures a FantasyTeam adheres to standard drafting constraints.
func ValidateTeam(team FantasyTeam, squadMap map[string]Player) error {
	if len(team.PlayerIDs) != 11 {
		return ErrInvalidTeamSize
	}
	if team.CaptainID == "" || team.ViceCaptainID == "" {
		return errors.New("both captain and vice-captain must be specified")
	}
	if team.CaptainID == team.ViceCaptainID {
		return ErrCaptainVCSame
	}

	seen := make(map[string]bool, 11)
	teamCounts := make(map[string]int)
	captainFound := false
	vcFound := false

	for _, pid := range team.PlayerIDs {
		if seen[pid] {
			return ErrDuplicatePlayer
		}
		seen[pid] = true

		p, ok := squadMap[pid]
		if !ok {
			return fmt.Errorf("%w: %s", ErrUnknownPlayer, pid)
		}
		teamCounts[p.Team]++
		if teamCounts[p.Team] > 7 {
			return ErrMaxPlayersFromTeam
		}

		if pid == team.CaptainID {
			captainFound = true
		}
		if pid == team.ViceCaptainID {
			vcFound = true
		}
	}

	if !captainFound {
		return ErrCaptainNotSelected
	}
	if !vcFound {
		return ErrVCNotSelected
	}

	return nil
}

// CloneStats creates a deep copy of the running stats map.
func CloneStats(src map[string]PlayerRunningStats) map[string]PlayerRunningStats {
	dst := make(map[string]PlayerRunningStats, len(src))
	for k, v := range src {
		dst[k] = v
	}
	return dst
}

// PointsForBall calculates the deterministic point deltas generated by a single ball delivery.
// Returns per-player point delta and updated player statistics.
func PointsForBall(ball BallEvent, statsBefore map[string]PlayerRunningStats) (map[string]float64, map[string]PlayerRunningStats) {
	deltas := make(map[string]float64)
	newStats := CloneStats(statsBefore)

	// Helper to get or init stats
	getStats := func(id string) PlayerRunningStats {
		if id == "" {
			return PlayerRunningStats{}
		}
		return newStats[id]
	}

	// 1. Batting scoring for striker
	if ball.StrikerID != "" {
		st := getStats(ball.StrikerID)
		var strikerDelta float64

		if ball.ExtraType != "wide" {
			st.BallsFaced++
		}

		if ball.RunsOffBat > 0 {
			st.Runs += ball.RunsOffBat
			strikerDelta += float64(ball.RunsOffBat) // +1 per run
		}

		if ball.IsBoundary4 {
			st.Fours++
			strikerDelta += 4.0 // +4 four bonus
		}

		if ball.IsSix {
			st.Sixes++
			strikerDelta += 6.0 // +6 six bonus
		}

		// Milestone bonuses
		if st.Runs >= 50 && !st.Milestone50Awarded {
			if st.Milestone30Awarded {
				strikerDelta += 8.0 // 16 - 8 = +8 incremental
			} else {
				strikerDelta += 16.0
			}
			st.Milestone30Awarded = true
			st.Milestone50Awarded = true
		} else if st.Runs >= 30 && !st.Milestone30Awarded && st.Runs < 50 {
			strikerDelta += 8.0
			st.Milestone30Awarded = true
		}

		st.TotalPoints += strikerDelta
		if strikerDelta != 0 {
			deltas[ball.StrikerID] += strikerDelta
		}
		newStats[ball.StrikerID] = st
	}

	// 2. Dismissals
	if ball.Wicket != nil {
		outID := ball.Wicket.PlayerOut
		if outID == "" {
			outID = ball.StrikerID
		}
		outStats := getStats(outID)
		outStats.IsOut = true

		// Duck penalty: out for 0 runs
		if outStats.Runs == 0 {
			duckPenalty := -2.0
			outStats.TotalPoints += duckPenalty
			deltas[outID] += duckPenalty
		}
		newStats[outID] = outStats

		// Bowler wicket bonus: +25 pts (excluding run outs)
		if ball.Wicket.Kind != "run_out" && ball.BowlerID != "" {
			bStats := getStats(ball.BowlerID)
			bStats.Wickets++
			wicketBonus := 25.0
			bStats.TotalPoints += wicketBonus
			deltas[ball.BowlerID] += wicketBonus
			newStats[ball.BowlerID] = bStats
		}
	}

	// 3. Bowling overs & maidens
	if ball.BowlerID != "" {
		bStats := getStats(ball.BowlerID)
		isLegal := ball.ExtraType != "wide" && ball.ExtraType != "no_ball"

		if isLegal {
			bStats.BallsBowledInOver++
			bStats.RunsConcededInOver += ball.RunsOffBat + ball.Extras

			if bStats.BallsBowledInOver == 6 {
				// Completed an over
				bStats.OversBowled++
				if bStats.RunsConcededInOver == 0 {
					// Maiden over bonus: +4 pts
					maidenBonus := 4.0
					bStats.TotalPoints += maidenBonus
					deltas[ball.BowlerID] += maidenBonus
				}
				bStats.BallsBowledInOver = 0
				bStats.RunsConcededInOver = 0
			}
		} else {
			bStats.RunsConcededInOver += ball.RunsOffBat + ball.Extras
		}
		newStats[ball.BowlerID] = bStats
	}

	return deltas, newStats
}

// TeamScore computes total fantasy points for a team given cumulative player points.
func TeamScore(team FantasyTeam, playerPoints map[string]float64) float64 {
	var total float64
	for _, pid := range team.PlayerIDs {
		pts := playerPoints[pid]
		if pid == team.CaptainID {
			pts *= 2.0
		} else if pid == team.ViceCaptainID {
			pts *= 1.5
		}
		total += pts
	}
	return total
}

// ApplyBall calculates member deltas, updated totals, and rank changes after a ball delivery.
func ApplyBall(
	ball BallEvent,
	statsBefore map[string]PlayerRunningStats,
	teams []FantasyTeam,
	oldTotals map[string]float64,
) (
	memberDeltas map[string]float64,
	newTotals map[string]float64,
	playerDeltas map[string]float64,
	newStats map[string]PlayerRunningStats,
	rankChanges []RankChange,
) {
	playerDeltas, newStats = PointsForBall(ball, statsBefore)

	memberDeltas = make(map[string]float64, len(teams))
	newTotals = make(map[string]float64, len(teams))

	for _, t := range teams {
		var d float64
		for _, pid := range t.PlayerIDs {
			pts := playerDeltas[pid]
			if pts == 0 {
				continue
			}
			if pid == t.CaptainID {
				pts *= 2.0
			} else if pid == t.ViceCaptainID {
				pts *= 1.5
			}
			d += pts
		}
		memberDeltas[t.UserID] = d
		newTotals[t.UserID] = oldTotals[t.UserID] + d
	}

	// Rank calculation
	type userScore struct {
		userID   string
		username string
		score    float64
	}

	computeRanks := func(totals map[string]float64) map[string]int {
		list := make([]userScore, 0, len(teams))
		for _, t := range teams {
			list = append(list, userScore{
				userID:   t.UserID,
				username: t.Username,
				score:    totals[t.UserID],
			})
		}
		// Sort descending by score, tie-break by userID
		sort.Slice(list, func(i, j int) bool {
			if list[i].score != list[j].score {
				return list[i].score > list[j].score
			}
			return list[i].userID < list[j].userID
		})
		ranks := make(map[string]int, len(list))
		for i, item := range list {
			ranks[item.userID] = i + 1
		}
		return ranks
	}

	oldRanks := computeRanks(oldTotals)
	curRanks := computeRanks(newTotals)

	rankChanges = make([]RankChange, 0, len(teams))
	for _, t := range teams {
		rankChanges = append(rankChanges, RankChange{
			UserID:      t.UserID,
			Username:    t.Username,
			OldRank:     oldRanks[t.UserID],
			NewRank:     curRanks[t.UserID],
			PointsDelta: memberDeltas[t.UserID],
			NewTotal:    newTotals[t.UserID],
		})
	}

	// Sort rank changes by new rank
	sort.Slice(rankChanges, func(i, j int) bool {
		return rankChanges[i].NewRank < rankChanges[j].NewRank
	})

	return memberDeltas, newTotals, playerDeltas, newStats, rankChanges
}
